'use client';

import React from 'react';
import dynamic from 'next/dynamic';
import SectionCard from '../shared/SectionCard';
import TagChip from '../shared/TagChip';
import { useArchitectureDiagram } from '@/hooks/useArchitectureDiagram';
import { GitBranch, Sparkles, AlertCircle } from 'lucide-react';
import { CircularProgress } from '@wso2/oxygen-ui';

const MermaidRenderer = dynamic(() => import('./MermaidRenderer'), {
  ssr: false,
  loading: () => (
    <div className="flex flex-col items-center justify-center p-10 space-y-3">
      <CircularProgress size={28} className="text-indigo-500" />
      <span className="text-xs text-slate-400 font-medium">Loading diagram renderer...</span>
    </div>
  ),
});

export default function ArchitectureGraph() {
  const { mermaidCode, isLoading, error, generate, hasData, wasCached } = useArchitectureDiagram();

  const badge = hasData ? (
    <TagChip label={wasCached ? 'Cached' : 'AI Generated'} category={wasCached ? 'framework' : 'frontend'} />
  ) : null;

  return (
    <SectionCard
      title="System Architecture Diagram"
      subtitle="High-level component architecture generated by AI from deep analysis."
      icon={<GitBranch className="h-5 w-5 text-indigo-400" />}
      badge={badge}
      collapsible={hasData}
    >
      {/* Initial state — show generate button */}
      {!hasData && !isLoading && !error && (
        <div className="flex flex-col items-center justify-center py-10 space-y-5">
          <div className="flex flex-col items-center gap-3 text-center max-w-sm">
            <div className="w-14 h-14 rounded-2xl bg-indigo-500/10 border border-indigo-500/20 flex items-center justify-center">
              <GitBranch className="h-7 w-7 text-indigo-400" />
            </div>
            <div>
              <p className="text-slate-200 font-semibold text-sm mb-1">Generate Architecture Diagram</p>
              <p className="text-slate-500 text-xs leading-relaxed">
                AI will analyze the system architecture and data flow to produce a high-level Mermaid diagram of this repository.
              </p>
            </div>
          </div>
          <button
            type="button"
            id="generate-architecture-diagram-btn"
            onClick={() => generate()}
            className="group flex items-center gap-2.5 px-5 py-2.5 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white text-sm font-semibold transition-all duration-200 shadow-lg shadow-indigo-900/40 hover:shadow-indigo-800/50 hover:scale-[1.02] active:scale-[0.99]"
          >
            <Sparkles className="h-4 w-4 group-hover:animate-pulse" />
            Generate Diagram
          </button>
        </div>
      )}

      {/* Loading state */}
      {isLoading && (
        <div className="flex flex-col items-center justify-center py-12 space-y-4">
          <div className="relative">
            <CircularProgress size={40} className="text-indigo-500" />
            <div className="absolute inset-0 flex items-center justify-center">
              <GitBranch className="h-4 w-4 text-indigo-400" />
            </div>
          </div>
          <div className="text-center space-y-1">
            <p className="text-slate-300 text-sm font-medium">AI is analyzing architecture...</p>
            <p className="text-slate-500 text-xs">This may take 15–30 seconds</p>
          </div>
          <div className="flex items-center gap-1.5 mt-1">
            {[0, 1, 2].map((i) => (
              <div
                key={i}
                className="w-1.5 h-1.5 rounded-full bg-indigo-500 animate-bounce"
                style={{ animationDelay: `${i * 0.15}s` }}
              />
            ))}
          </div>
        </div>
      )}

      {/* Error state */}
      {error && !hasData && (
        <div className="flex flex-col items-center gap-4 py-8">
          <div className="flex items-center gap-2.5 px-4 py-3 rounded-xl bg-red-950/40 border border-red-800/50 max-w-md w-full">
            <AlertCircle className="h-4 w-4 text-red-400 flex-shrink-0" />
            <div>
              <p className="text-red-300 text-xs font-semibold">Generation failed</p>
              <p className="text-red-400/80 text-xs mt-0.5 break-words">
                {error instanceof Error ? error.message : 'Unknown error occurred'}
              </p>
            </div>
          </div>
          <button
            type="button"
            onClick={() => generate(true)}
            className="flex items-center gap-2 px-4 py-2 rounded-xl bg-indigo-600/20 border border-indigo-500/40 text-indigo-300 text-sm font-medium hover:bg-indigo-600/30 transition-colors"
          >
            <Sparkles className="h-4 w-4" />
            Try Again
          </button>
        </div>
      )}

      {/* Diagram rendered */}
      {hasData && mermaidCode && (
        <MermaidRenderer
          code={mermaidCode}
          onRegenerate={() => generate(true)}
          isRegenerating={isLoading}
        />
      )}
    </SectionCard>
  );
}
